// Одно замечание движка правил — в том виде, в каком его читает панель
// «Проверки» и проверяют тесты.
//
//   { ruleId, level, basis, message, detail, hint,
//     clause, constraint, page, rationale, targets: [id…], diagramId }
//
// `message` — короткая формулировка нарушения из набора правил (одна на
// правило), `detail` — что именно нашла проверка в этой модели. Обе нужны:
// первая переводит правило на человеческий язык, вторая говорит, какой
// элемент и чем виноват.
//
// `basis` говорит, откуда правило: `uml` — констрейнт стандарта, `practice` —
// совет практики моделирования, `project` — соглашение команды из файла
// модели, `geometry` — проверка раскладки ЛИСТА (перенесена из archify 3.0.1:
// пересечения рамок, имя шире фигуры, мелкий текст на широком листе). Отсюда и
// разная обвязка: у правила стандарта есть пункт, имя констрейнта и страница, а
// объяснения «почему это запах» нет; у правила практики наоборот — ссылаться не
// на что, зато есть `rationale`; у правила проекта нет ни пункта, ни rationale:
// оно не требование UML и не совет по моделированию, а договорённость, которую
// команда записала сама; у замечания геометрии нет и их: оно про то, что где
// нарисовано, а не про то, что модель утверждает.
// Панель по `basis` раскладывает замечания по четырём разделам и рисует у
// практики, проекта и геометрии чип вместо кнопки пункта, поэтому поля не
// смешиваются: практика никогда не покажет пустой «п.», а стандарт — пустое
// объяснение.
//
// `targets` — id элементов и связей модели (не фигур и не связей-видов):
// замечание живёт в модели, а вид на него ищет панель. Пустой список значит
// «виноватого назвать нечем» — так бывает только у правил уровня модели.
//
// `diagramId` — лист, к которому относится замечание, или `null`. В модели у
// элемента может быть несколько фигур, и без листа панель не знает, куда вести
// при клике: имя листа в `detail` — строка текста, по ней не перейти. Ставит
// его только правило, которое судит лист (`shape-isolated-on-diagram`); правила
// стандарта говорят о модели, а не о листе, поэтому у них всегда `null`, и
// `null` — законное значение «лист не назван», а не пропуск данных.
//
// `status` есть только у записи-сбоя (`failure`): `status: 'failed'` значит
// «правило не смогло проверить модель». У обычного замечания поля нет вовсе —
// отсутствие `status` и есть «это нарушение модели», поэтому пустую строку сюда
// не пишут: иначе панель пришлось бы учить различать два вида «нет».

export function report(rule, targets, detail, opts = {}) {
  const basis = basisOf(rule);
  const practice = basis === 'practice';
  // У правила проекта нет ни пункта, ни констрейнта, ни страницы, ни
  // rationale: сослаться можно только на сам файл модели.
  const project = basis === 'project';
  // У замечания геометрии ссылаться тем более не на что: стандарт UML не
  // требует, чтобы фигуры не перекрывались, — это свойство картинки, а не
  // модели. Пустые пункт/констрейнт/страница здесь означают «такого поля у
  // слоя нет», а не «данные потерялись».
  const geometry = basis === 'geometry';
  const silent = practice || project || geometry;
  return {
    ruleId: rule.id,
    level: rule.level,
    basis,
    message: rule.message,
    detail: detail ?? '',
    hint: rule.hint,
    clause: silent ? null : (rule.source?.clause ?? null),
    constraint: silent ? null : (rule.source?.constraint ?? null),
    page: silent ? null : (rule.source?.page ?? null),
    rationale: practice ? (rule.rationale ?? null) : null,
    targets: (Array.isArray(targets) ? targets : [targets]).filter((id) => id != null).map(String),
    diagramId: opts.diagramId ?? null,
  };
}

/** Слой правила; отсутствующее поле — стандарт (наборы до четвёртого слоя). */
const basisOf = (rule) => (rule?.basis === 'practice'
  || rule?.basis === 'project'
  || rule?.basis === 'geometry'
  ? rule.basis
  : 'uml');

/**
 * Замечание-сбой: правило не смогло прочитать модель и было отключено до конца
 * прогона (см. `run` в `engine.js`).
 *
 * Это не замечание о модели, а отказ проверки, поэтому у него свой `status`:
 * отсутствие `status` — нарушение модели, `status: 'failed'` — сбой. Панель и
 * счётчики раскладывают такие записи отдельно, иначе человек прочитал бы «модель
 * плохая» там, где на самом деле не отработала проверка. `targets` пуст: винить
 * некого — правило не дошло до разбора элементов.
 *
 * Остальные поля — те же, что у `report`: у стандарта пункт и страница, у
 * практики `null` и rationale, чтобы строка сбоя не притворялась другим слоем.
 */
export function failure(rule, error) {
  const basis = basisOf(rule);
  const practice = basis === 'practice';
  const project = basis === 'project';
  const geometry = basis === 'geometry';
  const silent = practice || project || geometry;
  return {
    ruleId: rule.id,
    level: 'error',
    basis,
    message: `Правило «${rule.id}» не смогло проверить модель`,
    detail: `Проверка прервана ошибкой: ${error?.message ?? String(error)}`,
    hint: 'Это сбой проверки, а не замечание к модели: остальные правила отработали.',
    clause: silent ? null : (rule.source?.clause ?? null),
    constraint: silent ? null : (rule.source?.constraint ?? null),
    page: silent ? null : (rule.source?.page ?? null),
    rationale: practice ? (rule.rationale ?? null) : null,
    targets: [],
    diagramId: null,
    status: 'failed',
  };
}

/**
 * Счётчики замечаний по слоям.
 *
 * `errors` / `warnings` / `total` считают только слой стандарта: это прежние
 * числа статусбара, и привычка к ним не должна поехать от появления советов.
 * `advice` — отдельный счётчик слоя практики; в `warnings` он не подмешивается,
 * иначе «предупреждений» стало бы больше без единого нового нарушения стандарта.
 *
 * `project` — третий счётчик: замечания правил проекта. Он тоже не входит ни
 * в `warnings`, ни в `total`: соглашение команды не нарушение стандарта, и
 * прибавлять его к «предупреждениям UML» значило бы врать о модели в другую
 * сторону — будто стандарт стал строже.
 *
 * `layout` — четвёртый счётчик: замечания к раскладке листа. Они не входят ни
 * в `errors`, ни в `warnings`, ни в `total` по той же причине, только сильнее:
 * это замечания не к модели, а к картинке. Одна и та же верная модель с разной
 * раскладкой даёт разные числа, поэтому «предупреждений UML» они увеличивать не
 * должны — иначе счётчик перестал бы быть свойством модели.
 *
 * `failed` — сбои проверок (`status: 'failed'`) любого слоя. В `errors`,
 * `warnings`, `advice`, `project`, `layout` и `total` они не входят: упавшее
 * правило не нашло нарушения, оно не смогло искать, и считать его нарушением
 * значило бы врать о модели. При этом `failed` виден отдельно — «0 ошибок» при
 * упавшем правиле тоже было бы ложью.
 */
export function countByLevel(findings) {
  let errors = 0;
  let warnings = 0;
  let advice = 0;
  let project = 0;
  let layout = 0;
  let failed = 0;
  let total = 0;
  for (const f of findings) {
    if (f.status === 'failed') {
      failed += 1;
      continue;
    }
    if (f.basis === 'practice') {
      advice += 1;
      continue;
    }
    if (f.basis === 'project') {
      project += 1;
      continue;
    }
    // Без этой ветки замечание геометрии попало бы в `warnings` (его уровень —
    // «предупреждение») и испортило привычную цифру стандарта. Считаем его
    // отдельным слоем.
    if (f.basis === 'geometry') {
      layout += 1;
      continue;
    }
    if (f.level === 'error') errors += 1;
    else if (f.level === 'warning') warnings += 1;
    total += 1;
  }
  return { errors, warnings, advice, project, layout, failed, total };
}