// Путь цикла для правил, которые запрещают элемент быть своим собственным
// предком (`no_cycles_in_generalization`, `cannot_include_self`).
//
// Правило видит симптом — «элемент входит в собственные предки», — но человеку
// нужен путь: «A → B → C → A». Поэтому обход идёт от конкретного элемента и
// возвращает ровно ту цепочку, которая замыкается на него.
//
// Один модуль на оба правила: цикл обобщения и цикл включений отличаются только
// функцией `nextOf`, а поиск пути у них общий. Второй такой же обход в соседнем
// файле разошёлся бы с первым при первой правке.

/**
 * Найти путь `start → … → start`.
 *
 * `nextOf(id)` отдаёт массив id, куда ведут рёбра из `id`. Возвращает массив id
 * без повторного `start` в конце: для A→B→C→A — `[A, B, C]`, для петли A→A —
 * `[A]`. Если пути нет — `null`: правило тогда остаётся при прежнем тексте.
 *
 * Обход с возвратом: вершина, уже стоящая в текущем пути, второй раз не
 * берётся, а после тупика снимается со `seen` — иначе чужой цикл, встреченный
 * по дороге, навсегда закрыл бы законный путь через ту же вершину.
 */
export function cyclePath(start, nextOf) {
  const first = String(start);
  const path = [first];
  const seen = new Set([first]);

  const walk = (id) => {
    for (const next of nextOf(id) ?? []) {
      const to = String(next);
      if (to === first) return true;   // вернулись в начало — путь замкнулся
      if (seen.has(to)) continue;      // уже в пути: это не наш цикл
      seen.add(to);
      path.push(to);
      if (walk(to)) return true;
      path.pop();
      seen.delete(to);
    }
    return false;
  };

  return walk(first) ? path : null;
}
